# Apply replacements file-by-file
files_touched = {}
for fname, find, repl in REPLACEMENTS:
    p = ROOT / fname
    txt = files_touched.get(p)
    if txt is None:
        txt = p.read_text(encoding='utf-8')
    if find not in txt:
        print(f'SKIP (not found in {fname}): {find[:60]}...'.encode('ascii','replace').decode('ascii'), file=sys.stderr)
        files_touched[p] = txt
        continue
    txt = txt.replace(find, repl, 1)
    files_touched[p] = txt
    print(f'ok: {fname} <- {find[:60]}...'.encode('ascii','replace').decode('ascii'))

for p, txt in files_touched.items():
    p.write_text(txt, encoding='utf-8')
    print(f'wrote {p.name}: {len(txt)} bytes')
